'use strict';
const fs = require('node:fs/promises');
const path = require('node:path');
const { validateCapability, PROVIDER_IDS } = require('../src/transfer/capabilities');

const COMMON = ['src/transfer/envelope.js', 'src/transfer/capabilities.js', 'src/transfer/browser/runtime.js', 'src/transfer/browser/ui.js', 'src/transfer/browser/source.js'];
// Source-only readers are separately reviewed implementations. Their presence
// never enables destination writes or asserts complete provider-pair acceptance.
const SOURCE_READERS = Object.freeze(Object.fromEntries(['appsample', 'hoyolab', 'kongying', 'bwiki'].map(id => [id, 'src/transfer/providers/' + id + '/reader.js'])));
function dependency(from, request, allowed) {
  if (!request.startsWith('.')) throw new Error('bundle-dependency');
  const base = path.posix.normalize(path.posix.join(path.posix.dirname(from), request));
  const found = [base, base + '.js', base + '.json'].find(name => allowed.has(name));
  if (!found) throw new Error('bundle-dependency'); return found;
}
async function exists(file) { try { await fs.access(file); return true; } catch { return false; } }

/** Build ten inspectable static CommonJS module tables. Source paths are a fixed allowlist;
 * no transfer file content is involved in code generation. New adapters can only require the
 * shared browser modules or their own reviewed normalize module, never arbitrary filesystem code.
 */
async function buildTransferScripts({ root }) {
  const output = [];
  for (const provider of PROVIDER_IDS) {
    const providerRoot = 'src/transfer/providers/' + provider;
    const capabilityPath = providerRoot + '/capability.json';
    const capability = validateCapability(JSON.parse(await fs.readFile(path.join(root, capabilityPath), 'utf8')));
    if (capability.provider !== provider) throw new Error('bundle-provider');
    const adapterPath = providerRoot + '/adapter.js';
    const hasAdapter = await exists(path.join(root, adapterPath));
    const files = [...COMMON, capabilityPath];
    const readerPath = SOURCE_READERS[provider];
    if (readerPath) files.push(readerPath);
    if (hasAdapter) files.push(adapterPath);
    if ((hasAdapter || readerPath) && await exists(path.join(root, providerRoot + '/normalize.js'))) files.push(providerRoot + '/normalize.js');
    const allowed = new Set(files); const indexes = new Map(files.map((name, i) => [name, i]));
    const modules = [];
    for (const file of files) {
      let source = await fs.readFile(path.join(root, file), 'utf8');
      if (file.endsWith('.json')) source = 'module.exports=' + JSON.stringify(JSON.parse(source)) + ';';
      else {
        // Runtime compilation/evaluated loaders and ambiguous require expressions are forbidden.
        if (/\b(?:eval|Function|import)\s*\(/.test(source.replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, ''))) throw new Error('bundle-dependency');
        source = source.replace(/\brequire\s*\(\s*(['"])([^'"]+)\1\s*\)/g, (_, quote, request) => { return '__staticRequire(' + indexes.get(dependency(file, request, allowed)) + ')'; });
        if (/\brequire\b/.test(source)) throw new Error('bundle-dependency');
        source = source.replace(/\b__staticRequire\(/g, 'require(');
      }
      modules.push(indexes.get(file) + ':function(require,module,exports){\n' + source + '\n}');
    }
    for (const direction of ['export', 'import']) {
      const unavailable = capability.status !== 'supported' || !hasAdapter;
      const reason = capability.reasonCode || (hasAdapter ? 'variant-acceptance-pending' : 'verified-adapter-implementation-pending');
      const entry = direction === 'export' && provider === 'mapgenie' && unavailable
        ? 'console.error("MapGenie export unavailable: source-verification-required. Current website access was blocked, so its active profile and saved-progress format could not be verified. No file was exported.");'
        : direction === 'export' && readerPath && unavailable
        ? sourceEntry(indexes.get(readerPath))
        : unavailable
        ? 'console.error(' + JSON.stringify(provider + ' ' + direction + ' unavailable: ' + reason + '. Use app-local progress files until a verified adapter and disposable-save acceptance are available.') + ');'
        : activeEntry(indexes.get(adapterPath), indexes.get('src/transfer/browser/runtime.js'), indexes.get('src/transfer/browser/ui.js'), indexes.get(capabilityPath), direction);
      const code = '/* Generated by tools/build-transfer-scripts.js. Inspect before pasting. No remote loader. */\n(async function(){\n\'use strict\';\nconst modules={\n' + modules.join(',\n') + '\n};\nconst cache=Object.create(null);\nfunction require(id){if(!Object.prototype.hasOwnProperty.call(modules,id))throw new Error("bundle-dependency");if(!cache[id]){const module={exports:{}};cache[id]=module;modules[id](require,module,module.exports);}return cache[id].exports;}\n' + entry + '\n})().catch(function(){console.error("Transfer unavailable: UI or verified adapter could not start. Respect site security; do not bypass CSP.");});\n';
      const target = path.join(root, 'src/transfer/scripts', provider + '-' + direction + '.js');
      await fs.mkdir(path.dirname(target), { recursive: true }); await fs.writeFile(target, code); output.push(target);
    }
  }
  return output;
}
function sourceEntry(readerId) {
  return `const {runSourceExport}=require(${readerId});
${downloadEntry()}
await runSourceExport({window,fetch,download,console});`;
}
function downloadEntry() {
  return `const download=async function(name,bytes){const url=URL.createObjectURL(new Blob([bytes],{type:'application/json'}));const link=document.createElement('a');try{link.href=url;link.download=name;document.body.appendChild(link);link.click();}finally{link.remove();setTimeout(function(){URL.revokeObjectURL(url);},1000);}};`;
}
function activeEntry(adapterId, runtimeId, uiId, capabilityId, direction) {
  return `const key=Symbol.for('genshin-map-overlay.browser-transfer');
const slot=globalThis[key]||(globalThis[key]={generation:0,current:null,draining:Promise.resolve(),pacing:new Map()});
const generation=++slot.generation;
if(slot.current){const old=slot.current;slot.current=null;slot.draining=Promise.all([slot.draining,old.dispose()]);}
await slot.draining;
if(generation!==slot.generation)return;
const {createAdapter}=require(${adapterId});
const capability=require(${capabilityId});
const {createBrowserTransfer}=require(${runtimeId});
const {createTransferUi}=require(${uiId});
const ui=createTransferUi(document);
${downloadEntry()}
let runner;
try{const adapter=createAdapter({window,fetch,capability});const variant=adapter.capability.variants.find(v=>v.id===adapter.variantId);if(!variant)throw new Error('adapter-unverified');const pacingKey=JSON.stringify([adapter.capability.provider,[...variant.origins].sort()]);let pacingState=slot.pacing.get(pacingKey);if(!pacingState){pacingState={notBefore:0,lastWriteAt:null};slot.pacing.set(pacingKey,pacingState);}runner=createBrowserTransfer({adapter,ui,download,pacingState,sleep:ms=>new Promise(resolve=>setTimeout(resolve,ms)),now:()=>performance.now()});}catch{ui.dispose();throw new Error('adapter-unavailable');}
slot.current=runner;
try{${direction === 'import' ? "const bytes=await ui.chooseFile();if(bytes&&generation===slot.generation)await runner.preview(bytes);" : 'await runner.exportProgress();'}}catch(error){if(generation===slot.generation)ui.showError( /^(?:file-scope-mismatch|catalog-mismatch|identity-unavailable|adapter-unverified|backup-unavailable|backup-incomplete|backup-download-failed|context-unavailable|context-changed|readback-unavailable|invalid-transfer|transfer-too-large)$/.test(error.code||'')?error.code:'transfer-unavailable');}`;
}
if (require.main === module) buildTransferScripts({ root: path.resolve(__dirname, '..') }).then(paths => process.stdout.write('Built ' + paths.length + ' transfer scripts.\n')).catch(error => { process.stderr.write('Transfer bundle build failed: ' + error.message + '\n'); process.exitCode = 1; });
module.exports = { buildTransferScripts };
